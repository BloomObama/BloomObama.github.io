import {createRequire} from 'node:module';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE,headless:true});
const check=(condition,message)=>{if(!condition)throw new Error(message);};
try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8765/index.html?lang=en',{waitUntil:'domcontentloaded'});
  check(await page.locator('link[rel="icon"][href="/favicon-av.png"]').count()===1,'home advertises AdmitVector favicon');
  check(await page.locator('.admission-orientation article').count()===3,'useful admission guidance is in HTML');
  check((await page.locator('#orientation-title').textContent()).includes('Which U.S. university'),'admission guidance localizes');
  await page.locator('#roi-toggle').click();
  check(await page.locator('#roi-panel').isVisible(),'calculator opens');
  check(await page.locator('#roi-panel').evaluate(el=>parseInt(getComputedStyle(el).borderTopLeftRadius)>15),'calculator shell is rounded');
  const before=await page.locator('#roi-total').textContent();
  await page.locator('#roi-tuition').fill('70000');
  check(await page.locator('#roi-total').textContent()!==before,'education math responds to input');
  await page.locator('[data-roi-mode="arrival"]').click();
  check(await page.locator('#roi-arrival').isVisible() && await page.locator('#roi-education').isHidden(),'arrival calculator is independent');
  const moveBefore=await page.locator('#roi-move-total').textContent();
  await page.locator('#roi-flight').fill('1200');
  check(await page.locator('#roi-move-total').textContent()!==moveBefore,'arrival math responds to input');
  await page.locator('[data-roi-mode="arrival"]').press('ArrowLeft');
  check(await page.locator('#roi-education').isVisible(),'calculator tabs support keyboard');
  await page.waitForTimeout(500);
  await page.screenshot({path:join(tmpdir(),'admitvector-roi-polish.png')});
  await page.goto('http://127.0.0.1:8765/ielts-resources.html?lang=en',{waitUntil:'domcontentloaded'});
  check(await page.locator('.exam-switch').count()===0,'redundant exam chooser removed');
  check(await page.locator('#ielts-score-chart').count()===1,'IELTS score tracker exists');
  const today=await page.evaluate(()=>{const d=new Date();return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;});
  await page.locator('#ielts-score-form [name="date"]').fill(today);
  await page.locator('#ielts-score-form [name="band"]').fill('6.5');
  await page.locator('#ielts-score-form button').click();
  await page.locator('#ielts-score-form [name="band"]').fill('7');
  await page.locator('#ielts-score-form button').click();
  check(await page.locator('#ielts-score-chart circle').count()===2,'IELTS chart draws two reported scores');
  check(await page.locator('#ielts-latest').textContent()==='7.0','latest IELTS band is shown');
  await page.reload({waitUntil:'domcontentloaded'});
  check(await page.locator('#ielts-score-chart circle').count()===2,'IELTS scores survive reload');
  await page.locator('[data-resource-lang="ru"]').click();
  check(await page.locator('#ielts-score-title').textContent()==='Следите за прогрессом','IELTS tracker localizes');
  await page.setViewportSize({width:390,height:844});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('#ielts-score-title').scrollIntoViewIfNeeded();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'IELTS mobile layout does not overflow');
  await page.screenshot({path:join(tmpdir(),'admitvector-ielts-score-mobile.png')});
  await page.goto('http://127.0.0.1:8765/sat-resources.html?lang=en',{waitUntil:'domcontentloaded'});
  check(await page.locator('.exam-switch').count()===0,'SAT branch has no redundant chooser');
  check(await page.locator('[data-rail-route="sat"]').getAttribute('aria-current')==='page','SAT is its own navigation branch');
  check(errors.length===0,'no page errors: '+errors.join('; '));
  console.log('PASS: favicon, admission guidance, ROI scenarios, IELTS score trend, SAT/IELTS split, mobile layout');
}finally{await browser.close();}
