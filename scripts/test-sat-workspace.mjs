import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE,headless:true});
const assert=(value,message)=>{if(!value)throw new Error(message);};
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8765/sat-resources.html?lang=en',{waitUntil:'domcontentloaded'});
  assert(await page.locator('[data-sat-step]').count()===4,'four independent route controls');
  await page.locator('[data-sat-step="plan"]').click();
  assert(await page.locator('#sat-workspace-title').textContent()==='Your study plan','plan panel opens');
  await page.locator('#sat-plan-form [name="date"]').fill('2027-06-01');
  await page.locator('#sat-plan-form [name="target"]').fill('1400');
  await page.locator('#sat-plan-form [name="days"]').selectOption('5');
  await page.locator('#sat-plan-form button[type="submit"]').click();
  assert(await page.locator('.sat-task-list button').count()===4,'plan tasks created');
  await page.locator('[data-sat-task="0"]').click();
  await page.locator('[data-sat-step="test"]').click();
  assert(await page.locator('#sat-workspace-title').textContent()==='Practice tests','test panel opens separately');
  await page.locator('#sat-test-form [name="score"]').fill('1250');
  await page.locator('#sat-test-form button[type="submit"]').click();
  assert((await page.locator('.sat-score-list').textContent()).includes('1250'),'practice score recorded');
  await page.locator('[data-sat-step="skills"]').click();
  assert(await page.locator('#sat-workspace-title').textContent()==='Weaker skills','skill panel opens separately');
  await page.locator('[data-sat-skill="algebra"]').click();
  await page.locator('[data-sat-step="habit"]').click();
  assert(await page.locator('#sat-workspace-title').textContent()==='Study routine','routine panel opens separately');
  await page.locator('#sat-session-form [name="minutes"]').fill('30');
  await page.locator('#sat-session-form button[type="submit"]').click();
  const progress=await page.locator('#sat-progress-percent').textContent();
  assert(Number.parseInt(progress)>0,'real actions advance progress');
  await page.reload({waitUntil:'domcontentloaded'});
  assert(await page.locator('#sat-progress-percent').textContent()===progress,'progress survives reload');
  await page.locator('[data-sat-step="plan"]').click();
  assert(await page.locator('#sat-plan-form [name="target"]').inputValue()==='1400','plan survives reload');
  assert(await page.locator('[data-sat-task="0"]').getAttribute('aria-pressed')==='true','completed task survives reload');
  await page.waitForTimeout(650);
  await page.screenshot({path:join(tmpdir(),'admitvector-sat-workspace-desktop.png')});
  await page.locator('[data-sat-lang="ru"]').click();
  assert(await page.locator('#sat-workspace-title').textContent()==='Ваш план подготовки','panel localizes');
  await page.setViewportSize({width:390,height:844});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('[data-sat-step="plan"]').click();
  await page.waitForTimeout(650);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile layout has no horizontal overflow');
  await page.screenshot({path:join(tmpdir(),'admitvector-sat-workspace-mobile.png')});
  await page.evaluate(()=>FullRidePreferences.update({interface:{theme:'dark',reduceMotion:true}}));
  assert(await page.locator('.sat-hero__seal').evaluate(el=>getComputedStyle(el).animationName)==='none','reduced motion disables hero animation');
  assert(await page.locator('.sat-workspace').evaluate(el=>getComputedStyle(el).backgroundColor)==='rgb(47, 36, 45)','dark panel uses matching palette');
  await page.evaluate(()=>FullRidePreferences.setAccount('sat-test-account'));
  assert(await page.locator('#sat-progress-percent').textContent()==='0%','another account does not inherit guest progress');
  await page.evaluate(()=>FullRidePreferences.setAccount(null));
  assert(await page.locator('#sat-progress-percent').textContent()===progress,'guest progress returns after account switch');
  assert(errors.length===0,'no runtime errors: '+errors.join('; '));
  console.log('PASS: four SAT panels, plan/tasks, score, skill, session, persistent progress, localization, mobile layout');
}finally{await browser.close();}
