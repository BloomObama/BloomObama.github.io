import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import policy from "../policy-core.js";
import { validateReview, readJSON } from "./policy-pipeline-core.mjs";
import { buildSeoPages } from "./build-seo-pages.mjs";

const root = path.resolve(import.meta.dirname, "..");
const sources = ["college-catalog.js", "college-directory.js", "college-media.js", "college-policies.js", "data.js"];
const context = vm.createContext({ console });
context.globalThis = context;

for (const source of sources) {
  const code = fs.readFileSync(path.join(root, source), "utf8");
  vm.runInContext(code, context, { filename:source });
}
vm.runInContext("globalThis.__runtimeColleges = colleges", context);

const colleges = context.__runtimeColleges;
const reviews = readJSON('data/policy-field-reviews.json');
const manifest = readJSON('data/policy-source-manifest.json');
if (reviews.schemaVersion !== 1 || reviews.cycle !== policy.cycle) throw new Error('Invalid field review schema');
for (const [id, record] of Object.entries(reviews.records)) validateReview(id, record, colleges, manifest);
colleges.forEach(college => policy.apply(college, reviews.records[college.catalogId]));
const shardCount = 128;
const outputDirectory = path.join(root, "data", "college-details");
fs.mkdirSync(outputDirectory, { recursive:true });

const shardFor = slug => {
  let hash = 2166136261;
  for (const character of slug) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0) % shardCount;
};

const compact = value => value === undefined ? null : value;
const thumbnailUrl = value => String(value || "")
  .replace(/\/1920px-/i, "/960px-")
  .replace(/([?&])width=2000(?=&|$)/i, "$1width=960")
  .replace(/[?&]$/, "");
const rows = colleges.map(college => {
  const shard = shardFor(college.slug);
  const flags = (college.verified ? 1 : 0)
    | (college.basicOnly ? 2 : 0)
    | (college.descriptionPending ? 4 : 0)
    | (college.photoIsIllustrative ? 8 : 0)
    | (college.needBlind ? 16 : 0)
    | (college.testFlexible ? 32 : 0)
    | (college.feeWaiver ? 64 : 0)
    | (college.needBlind == null ? 128 : 0)
    | (college.testFlexible == null ? 256 : 0)
    | (college.feeWaiver == null ? 512 : 0);
  const verifiedDetail = college.verified ? [
    compact(college.checkedAt)
  ] : null;
  const row = [
    college.slug, college.name, college.short, college.location,
    college.region, college.state, college.institutionType, college.setting, college.aidCategory,
    college.focus || [], compact(college.englishStatus), compact(college.catalogId),
    shard.toString(16).padStart(2, "0"), [...(college.facts?.topFields || []), ...(college.focus || [])].join(" "),
    flags, verifiedDetail,
    [college.facts?.control, college.facts?.predominantDegree, college.facts?.tuitionOut, college.facts?.enrollment].map(compact)
  ];
  // Only reviewed exceptions get metadata in the search index; 5,002 empty objects would waste bandwidth.
  if (reviews.records[college.catalogId] && !college.verified) row.push(policy.count(college) | (policy.fields.reduce((mask,key,i)=>mask|(policy.known(college,key)?1<<i:0),0)<<3));
  return row;
});

const indexSource = `/* Generated by scripts/build-runtime-data.mjs. Do not edit directly. */\nconst collegeIndexRows=${JSON.stringify(rows)};\nconst colleges=collegeIndexRows.map(r=>{const f=r[14],v=r[15]||[];return{slug:r[0],name:r[1],short:r[2],location:r[3],description:"",source:"",photo:"assets/campus-placeholder.svg",photoThumb:"assets/campus-placeholder.svg",region:r[4],state:r[5],institutionType:r[6],setting:r[7],aidCategory:r[8],focus:r[9],englishStatus:r[10],catalogId:r[11],_detailShard:r[12],_searchText:r[13],verified:Boolean(f&1),basicOnly:Boolean(f&2),descriptionPending:Boolean(f&4),photoIsIllustrative:Boolean(f&8),needBlind:Boolean(f&16),testFlexible:Boolean(f&32),feeWaiver:Boolean(f&64),checkedAt:v[0]||null,aidShort:v[1]||null,aid:v[2]||null,testing:v[3]||null,english:v[4]||null,fee:v[5]||null,deadline:v[6]||null,aidSource:v[7]||null,testingSource:v[8]||null,englishSource:v[9]||null,feeSource:v[10]||null,deadlineSource:v[11]||null,_detailsLoaded:false}});\n`;
const finderSource = '\ncolleges.forEach((college,i)=>{const f=collegeIndexRows[i][16]||[];college.finderFacts={control:f[0],degree:f[1],tuition:f[2],enrollment:f[3]};const flags=collegeIndexRows[i][14];if(flags&128)college.needBlind=null;if(flags&256)college.testFlexible=null;if(flags&512)college.feeWaiver=null;const r=collegeIndexRows[i][17];if(r!=null){college.policyCoverage=r&7;college.policyMask=(r>>3)&31;}});\n';
fs.writeFileSync(path.join(root, "college-index.js"), indexSource + finderSource);

const details = Array.from({ length:shardCount }, () => ({}));
for (const college of colleges) {
  const shard = shardFor(college.slug);
  details[shard][college.slug] = {
    facts:college.facts || null,
    description:college.description,
    source:college.source,
    photo:college.photo,
    photoThumb:thumbnailUrl(college.photo),
    photoSource:compact(college.photoSource),
    photoCredit:compact(college.photoCredit),
    _detailsLoaded:true
  };
  if (reviews.records[college.catalogId]) details[shard][college.slug].policyFields = college.policyFields;
  if (college.verified || reviews.records[college.catalogId]) {
    for (const key of [...policy.fields,...policy.fields.map(key=>key+'Source'),'aidShort','needBlind','testFlexible','feeWaiver']) details[shard][college.slug][key] = compact(college[key]);
  }
}

details.forEach((shard, index) => {
  const name = index.toString(16).padStart(2, "0");
  fs.writeFileSync(path.join(outputDirectory, `${name}.json`), JSON.stringify(shard));
});

const siteRoot = "https://www.admitvector.com/";
const seoProfiles = buildSeoPages({root,colleges,policy});
const sitemapUrls = ["", "practice", "ielts-resources", "sat-resources", "guide", "universities/"]
  .map(page => `${siteRoot}${page}`)
  .concat(seoProfiles.map(profile => `${siteRoot}universities/${profile.slug}`));
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemapUrls.map(url => `  <url><loc>${url.replace(/&/g, "&amp;")}</loc></url>`).join("\n")}\n</urlset>\n`;
fs.writeFileSync(path.join(root, "sitemap.xml"), sitemap);

const totalDetailBytes = fs.readdirSync(outputDirectory).reduce((sum, name) => sum + fs.statSync(path.join(outputDirectory, name)).size, 0);
console.log(JSON.stringify({ colleges:colleges.length, indexBytes:Buffer.byteLength(indexSource), detailShards:shardCount, detailBytes:totalDetailBytes, sitemapUrls:sitemapUrls.length }, null, 2));
